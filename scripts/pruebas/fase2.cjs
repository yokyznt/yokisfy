const { chromium } = require('playwright')
const out = process.env.OUT || '.'

;(async () => {
  const b = await chromium.connectOverCDP('http://127.0.0.1:9333')
  const page = b.contexts()[0].pages()[0]
  const errors = []
  page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
  const inv = (cmd, args = {}) => page.evaluate(([c, a]) => window.__TAURI_INTERNALS__.invoke(c, a), [cmd, args])
  const wait = (ms) => page.waitForTimeout(ms)
  const shot = (n) => page.screenshot({ path: `${out}/${n}.png` })
  const status = () => page.evaluate(() => ({ t: document.querySelector('.pb-title')?.textContent, play: document.querySelector('.pb-controls .play-btn')?.getAttribute('aria-label'), live: document.querySelector('.pb-seek .live-pill')?.textContent, err: document.querySelector('.pb-error')?.textContent }))
  await inv('volume', { v: 0 })
  await page.reload()
  await wait(1500)
  let t = Date.now()
  const home = await inv('home')
  console.log('home ms', Date.now() - t, home.map((s) => `${s.title}:${s.tracks.length + s.albums.length}`).join(' | '))
  await page.waitForSelector('.st-grid', { timeout: 30000 })
  await wait(1500)
  await shot('30-home')
  t = Date.now()
  const r = await inv('search', { q: 'lofi' })
  const by = (k) => r.tracks.filter((x) => x.source === k).length
  console.log('search ms', Date.now() - t, 'tracks', r.tracks.length, 'audius', by('audius'), 'archive', by('archive'), 'jamendo', by('jamendo'), 'albums', r.albums.length, 'stations', r.stations.length, 'warn', r.warnings)
  const au = r.tracks.find((x) => x.source === 'audius')
  await inv('play', { tracks: [au], start: 0 })
  await page.waitForFunction(() => document.querySelector('.pb-controls .play-btn')?.getAttribute('aria-label') === 'Pausar' && !document.querySelector('.pb-controls .spin'), null, { timeout: 40000 })
  await wait(3000)
  console.log('audius', au.title, au.downloadable, au.formats.map((f) => f.label), JSON.stringify(await status()), await page.$$eval('.pb-seek .time', (e) => e.map((x) => x.textContent)))
  await inv('seek', { secs: 60 })
  await wait(2500)
  console.log('audius seek', await page.$$eval('.pb-seek .time', (e) => e.map((x) => x.textContent)))
  const st = r.stations[0] || (await inv('stations', { q: 'jazz' }))[0]
  await inv('play', { tracks: [st], start: 0 })
  await page.waitForFunction(() => document.querySelector('.pb-controls .play-btn')?.getAttribute('aria-label') === 'Pausar' && !document.querySelector('.pb-controls .spin'), null, { timeout: 40000 })
  await wait(5000)
  console.log('radio', st.title, JSON.stringify(await status()))
  await shot('31-radio')
  await page.click('.side-link:has-text("Buscar")')
  await page.fill('.search-bar input', 'jazz')
  await page.waitForSelector('.st-grid', { timeout: 40000 })
  await wait(1200)
  await shot('32-search')
  t = Date.now()
  const n = await inv('start_radio', { track: au })
  console.log('start_radio', n, 'ms', Date.now() - t)
  await wait(4000)
  const q = await page.evaluate(() => 0)
  console.log('queue after radio', JSON.stringify(await status()))
  const one = r.tracks.filter((x) => x.source === 'audius' && x.duration > 20).sort((a, b) => a.duration - b.duration)[0]
  await inv('repeat', { mode: 'off' })
  await inv('play', { tracks: [one], start: 0 })
  await page.waitForFunction(() => !document.querySelector('.pb-controls .spin') && document.querySelector('.pb-controls .play-btn')?.getAttribute('aria-label') === 'Pausar', null, { timeout: 40000 })
  await inv('seek', { secs: one.duration - 3 })
  t = Date.now()
  await page.waitForFunction((title) => document.querySelector('.pb-title')?.textContent && document.querySelector('.pb-title').textContent !== title, one.title, { timeout: 40000 }).catch(() => null)
  console.log('autoradio', Date.now() - t, 'ms', JSON.stringify(await status()))
  await page.click('.side-link:has-text("Ajustes")').catch(() => {})
  await wait(800)
  await shot('33-settings')
  await inv('toggle').catch(() => {})
  console.log('errors', JSON.stringify(errors))
  process.exit(0)
})().catch((e) => {
  console.error('FAIL', e.message.split('\n')[0])
  process.exit(1)
})
