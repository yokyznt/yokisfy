const { chromium } = require('playwright')
const fs = require('fs')

;(async () => {
  const b = await chromium.connectOverCDP('http://127.0.0.1:9333')
  const page = b.contexts()[0].pages()[0]
  const inv = (cmd, args = {}) => page.evaluate(([c, a]) => window.__TAURI_INTERNALS__.invoke(c, a), [cmd, args])
  await inv('volume', { v: 0 })
  const s = await inv('settings')
  console.log('jamendo_available', s.jamendo_available)
  let t = Date.now()
  const home = await inv('home')
  console.log('home ms', Date.now() - t, home.map((x) => `${x.title}:${x.tracks.length + x.albums.length}`).join(' | '))
  t = Date.now()
  const r = await inv('search', { q: 'piano' })
  const jm = r.tracks.filter((x) => x.source === 'jamendo')
  console.log('search ms', Date.now() - t, 'jamendo tracks', jm.length, 'jamendo albums', r.albums.filter((a) => a.source === 'jamendo').length, 'warn', r.warnings)
  const tr = jm.find((x) => x.downloadable && x.formats.some((f) => f.kind === 'flac'))
  console.log('track', tr.title, tr.formats.map((f) => f.label), tr.license)
  await inv('delete_download', { id: tr.id })
  tr.localPath = null
  t = Date.now()
  await inv('play', { tracks: [tr], start: 0 })
  await page.waitForFunction(() => document.querySelector('.pb-controls .play-btn')?.getAttribute('aria-label') === 'Pausar' && !document.querySelector('.pb-controls .spin'), null, { timeout: 40000 })
  console.log('start ms', Date.now() - t)
  await page.waitForTimeout(3000)
  console.log('tag', await page.textContent('.pb-right .tag'), await page.$$eval('.pb-seek .time', (e) => e.map((x) => x.textContent)))
  t = Date.now()
  await inv('seek', { secs: 600 })
  await page.waitForFunction(() => { const s = document.querySelectorAll('.pb-seek .time')[0]?.textContent || ''; return s.startsWith('10:') || s.startsWith('11:') }, null, { timeout: 30000 }).catch(() => null)
  console.log('seek600 ms', Date.now() - t)
  await page.waitForTimeout(1500)
  console.log('seek', await page.$$eval('.pb-seek .time', (e) => e.map((x) => x.textContent)))
  const d = await inv('download', { track: tr, kind: 'FLAC' })
  const st = fs.statSync(d.localPath)
  const head = fs.readFileSync(d.localPath).subarray(0, 4).toString()
  console.log('download', d.localPath, st.size, head)
  if (tr.albumId) {
    const al = await inv('album', { id: tr.albumId })
    console.log('album', al.album.title, al.tracks.length)
  }
  const n = await inv('start_radio', { track: tr })
  console.log('radio', n)
  await inv('toggle')
  process.exit(0)
})().catch((e) => {
  console.error('FAIL', e.message.split('\n')[0])
  process.exit(1)
})
